#!/usr/bin/env node
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const MODEL = 'kael-local-hash-64-v1'
const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(SCRIPT_DIR, '../../..')
const DEFAULT_DOC = resolve(REPO_ROOT, 'docs/foundation/kael-knowledge-corpus.md')

const doc = readFileSync(DEFAULT_DOC, 'utf-8').replace(/\r\n/g, '\n')
const rows = [
  ...safetyRows(doc),
  ...legalRows(doc),
  ...serviceRows(doc),
]

if (rows.length < 35) {
  throw new Error(`Expected at least 35 B5 embedding rows, got ${rows.length}`)
}

process.stdout.write([
  '-- Plan §31 B5 embedding backfill for approved Kael knowledge corpus.',
  `-- Generated by kael-b5-generate-embedding-backfill using ${MODEL}.`,
  '',
  'begin;',
  '',
  ...rows.map(updateSql),
  'commit;',
  '',
].join('\n'))

function safetyRows(source) {
  return candidateRowsBetween(
    source,
    '## Candidate `worker_safety_patterns`',
    '## Candidate `legal_awareness_patterns`',
  ).map((cells) => {
    const text = [
      'worker safety',
      cells[2],
      cells[3],
      cells[4],
      cells[5],
      cells[6],
    ].join(' | ')
    return {
      table: 'worker_safety_patterns',
      keyColumn: 'pattern_key',
      key: cells[1],
      text,
    }
  })
}

function legalRows(source) {
  return candidateRowsBetween(
    source,
    '## Candidate `legal_awareness_patterns`',
    '## Candidate `service_knowledge_boxes` / Problem Hints',
  ).map((cells) => {
    const text = [
      'legal awareness',
      cells[2],
      cells[3],
      cells[4],
      cells[5],
    ].join(' | ')
    return {
      table: 'legal_awareness_patterns',
      keyColumn: 'pattern_key',
      key: cells[1],
      text,
    }
  })
}

function serviceRows(source) {
  return candidateRowsBetween(
    source,
    '## Candidate `service_knowledge_boxes` / Problem Hints',
    '## Sign-off Checklist',
  ).map((cells) => {
    const text = [
      'service knowledge',
      cells[1],
      cells[2],
    ].join(' | ')
    return {
      table: 'service_knowledge_boxes',
      keyColumn: 'service_type',
      key: cells[1],
      text,
    }
  })
}

function candidateRowsBetween(source, startMarker, endMarker) {
  const start = source.indexOf(startMarker)
  const end = source.indexOf(endMarker)
  if (start < 0 || end <= start) throw new Error(`Missing corpus section ${startMarker}`)
  return source
    .slice(start, end)
    .split('\n')
    .map(markdownCells)
    .filter((cells) => cells[0] === 'approved')
}

function markdownCells(line) {
  const trimmed = line.trim()
  if (!trimmed.startsWith('|') || !trimmed.endsWith('|')) return []
  return trimmed.slice(1, -1).split('|').map((cell) => cell.trim())
}

function updateSql(row) {
  const embedding = vectorLiteral(localSemanticEmbedding(row.text))
  return [
    `update public.${row.table}`,
    `set embedding = ${sqlString(embedding)}::extensions.vector(64),`,
    `    embedding_model = ${sqlString(MODEL)},`,
    `    embedding_text = ${sqlString(row.text)},`,
    '    embedding_updated_at = now(),',
    `    safe_metadata = safe_metadata || ${sqlString(JSON.stringify({
      embedding_model: MODEL,
      embedding_source: 'b5_backfill',
      embedding_text_version: 'b5-2026-06-04',
    }))}::jsonb,`,
    '    updated_at = now()',
    `where ${row.keyColumn} = ${sqlString(row.key)};`,
    '',
  ].join('\n')
}

function localSemanticEmbedding(text) {
  const vector = Array.from({ length: 64 }, () => 0)
  const tokens = text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .split(/[^a-z0-9]+/g)
    .filter((token) => token.length > 1)
    .slice(0, 80)
  for (const token of tokens) {
    vector[positiveHash(token) % vector.length] += 1
    for (let offset = 0; offset < token.length - 1; offset += 1) {
      vector[positiveHash(token.slice(offset, offset + 2)) % vector.length] += 0.25
    }
  }
  const norm = Math.sqrt(vector.reduce((sum, value) => sum + value * value, 0))
  return norm > 0 ? vector.map((value) => Math.round((value / norm) * 1_000_000) / 1_000_000) : vector
}

function positiveHash(value) {
  let hash = 2166136261
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index)
    hash = Math.imul(hash, 16777619)
  }
  return hash >>> 0
}

function vectorLiteral(values) {
  return `[${values.map((value) => Number.isFinite(value) ? value : 0).join(',')}]`
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}
