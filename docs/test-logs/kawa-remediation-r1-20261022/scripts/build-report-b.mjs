const final = JSON.parse(read('results/final-pass-summary.json'))
const exitOf = (name) => final.find((entry) => entry.name === name)?.exit
const pick = (text, pattern) => (pattern.exec(text) ?? [])[0]?.replace(/\s+/g, ' ').replaceAll('|', '/').trim() ?? 'not found'
