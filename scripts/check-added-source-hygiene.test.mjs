import { test } from 'node:test'
import assert from 'node:assert/strict'
import { analyzeHygiene } from './check-added-source-hygiene.mjs'

const PRODUCT = 'apps/mobile/lib/price.ts'
const PRODUCT_TSX = 'apps/mobile/components/card.tsx'

const change = (path, text) => ({
  path,
  added: text.split('\n').map((line, index) => ({ line: index + 1, text: line })),
  removed: [],
  content: text,
})

const watermarkLines = (findings) => findings.filter((finding) => finding.rule === 'watermark').map((finding) => finding.line)

test('clean control: plain production code raises no finding', () => {
  assert.deepEqual(analyzeHygiene(change(PRODUCT, 'export const n = 1\nexport const url = "https://example.com"')), [])
})

test('red fixture: a generated-with marker blocks', () => {
  assert.deepEqual(watermarkLines(analyzeHygiene(change(PRODUCT, 'export const note = "Generated with Claude Code"'))), [1])
})

test('red fixture: a commit trailer inside source blocks', () => {
  assert.deepEqual(watermarkLines(analyzeHygiene(change(PRODUCT, 'export const note = "Co-Authored-By: Someone"'))), [1])
})

test('red fixture: the robot emoji blocks', () => {
  const emoji = `export const label = "${String.fromCodePoint(0x1f916)}"`
  assert.deepEqual(watermarkLines(analyzeHygiene(change(PRODUCT, emoji))), [1])
})

test('red fixture: AI self-attribution blocks', () => {
  assert.deepEqual(watermarkLines(analyzeHygiene(change(PRODUCT, 'export const note = "generated by Codex"'))), [1])
})

test('red fixture: a license header blocks', () => {
  assert.deepEqual(watermarkLines(analyzeHygiene(change(PRODUCT, '// SPDX-License-Identifier: MIT\nexport const n = 1'))), [1])
})

test('negative control: model identifiers that contain the word Claude are not watermarks', () => {
  assert.deepEqual(analyzeHygiene(change(PRODUCT, 'export const model = "claude-sonnet-5-5"\nexport const tool = "claude-api"')), [])
})

test('watermarks are checked in test files as well', () => {
  assert.deepEqual(watermarkLines(analyzeHygiene(change('apps/mobile/lib/__tests__/x-test.ts', 'const n = "Generated with Claude"'))), [1])
})

test('paths outside the product roots are not judged', () => {
  assert.deepEqual(analyzeHygiene(change('scripts/tool.ts', 'export const n = "Generated with Claude"')), [])
  assert.deepEqual(analyzeHygiene(change('apps/mobile/lib/readme.md', 'Generated with Claude')), [])
})

test('comments are not this checker concern: they are judged by check-comment-discipline', () => {
  assert.deepEqual(analyzeHygiene(change(PRODUCT_TSX, 'export const n = 1 // a note')), [])
})
