// Contract ratchet for .claude/skills. check-skills-sync.mjs proves the mirror is byte-identical
// to the canonical copy; harness/check-manifest.mjs proves ids, inventory, and checksums line up.
// Neither one reads a skill body, so a skill can point every agent at a path that does not exist —
// which is how the session-memory skill shipped a write target that was both absent and gitignored,
// silently discarding the entry it was supposed to save. It also proves a skill can execute what it
// tells an agent to run: a named command that does not exist, and a declared readiness that the
// skill body contradicts, are the same defect wearing different clothes.
// Run via `pnpm skills:contracts`.
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SKILLS = resolve(root, '.claude/skills')

// A skill writes paths relative to whichever tree it governs, so a candidate counts as dead only
// after failing every one of these plus the skill's own directory.
const SEARCH_ROOTS = ['', 'governance', 'apps/mobile']
// Generated or machine-local: absent in a clean checkout, so absence proves nothing.
const UNTRACKED = [/(^|\/)node_modules\//, /(^|\/)\.temp\//, /^\.codebase-memory\//]
// AGENTS.md Workspace Layout: `~/.codex/` is the CLI's own config home and the repo must never
// contain a matching path. `.gitignore` ignores it, so anything written there is lost.
const FORBIDDEN = [[/\.codex\//i, 'references a `.codex/` path — the repo must never contain one (AGENTS.md Workspace Layout)']]
// `.agents/` is generated by scripts/sync-skills.mjs; a skill must never send an agent to edit it.
const MIRROR_WRITE = /(^|\s)(cp|mv|rm|Write|Edit)\s[^\n]*\.agents\//
const DESCRIPTOR_KEYS = ['display_name', 'short_description', 'default_prompt']
// `pnpm dlx`, `pnpm exec`, and flags are pnpm's own surface, not workspace script names.
const PNPM_PASSTHROUGH = new Set(['dlx', 'exec', 'install', 'add', 'remove', 'run', 'why', 'store'])
// Readiness is declared once in the harness manifest; the skill body has to agree with it, or the
// agent reading the skill and the ratchet reading the manifest believe different things.
const PRECONDITIONS = /^##\s+Preconditions\s*$/m
// A skill has to say how it ends, or it ends however the agent feels like ending it. `## Close` is
// where the stop rule lives — the sentence naming what this skill must not claim without evidence.
const CLOSE = /^##\s+Close\s*$/m
// A gated skill whose only answer to a missing dependency is "stop" contributes nothing on every
// machine that lacks it — which, for a daemon or a physical device, is most of them. `## Degraded
// lane` is where it says what it still does, so readiness selects a lane instead of an on/off switch.
const DEGRADED = /^##\s+Degraded lane\s*$/m

function pathCandidates(text) {
  const found = new Set()
  for (const [, raw] of text.matchAll(/`([^`\n]+)`/g)) {
    const value = raw.trim()
    if (!value.includes('/')) continue
    if (/\s/.test(value)) continue
    if (/[<>*]/.test(value)) continue
    if (/^https?:/.test(value)) continue
    if (value.startsWith('@')) continue
    if (!/^[A-Za-z0-9._-]+(\/[A-Za-z0-9._-]+)+\/?$/.test(value)) continue
    if (value.split('/').includes('..')) continue
    // Two bare segments with no extension read as an upstream org/repo slug, not a repo path.
    if (!value.endsWith('/') && !/\.[A-Za-z0-9]+$/.test(value)) continue
    if (UNTRACKED.some((pattern) => pattern.test(value))) continue
    found.add(value)
  }
  return [...found]
}

function resolves(candidate, skillDir) {
  for (const base of SEARCH_ROOTS) if (existsSync(resolve(root, base, candidate))) return true
  return existsSync(resolve(skillDir, candidate))
}

function checkDescriptor(id, skillDir, problems) {
  const file = join(skillDir, 'agents', 'openai.yaml')
  if (!existsSync(file)) {
    problems.push(`${id}: missing agents/openai.yaml — Codex needs an interface descriptor for every skill`)
    return
  }
  const text = readFileSync(file, 'utf8')
  if (!/^interface:\s*$/m.test(text)) problems.push(`${id}: agents/openai.yaml has no top-level \`interface:\` block`)
  for (const key of DESCRIPTOR_KEYS) {
    const value = new RegExp(`^\\s+${key}:\\s*"?([^"\\n]*)"?\\s*$`, 'm').exec(text)?.[1]?.trim()
    if (!value) problems.push(`${id}: agents/openai.yaml is missing a non-empty ${key}`)
    else if (key === 'default_prompt' && !value.includes(`$${id}`)) {
      problems.push(`${id}: default_prompt must name the skill as $${id} so Codex can invoke it`)
    }
  }
}

if (!existsSync(SKILLS)) {
  console.error('canonical skills dir missing: .claude/skills')
  process.exit(1)
}

const scripts = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')).scripts ?? {}
const manifest = JSON.parse(readFileSync(resolve(root, 'config/harness/manifest.json'), 'utf8'))
const skillEntries = manifest.entries.filter((entry) => entry.kind === 'repository-skill')
const readinessById = new Map(skillEntries.map((entry) => [entry.id, entry.readiness]))
const closeoutById = new Map(skillEntries.map((entry) => [entry.id, entry.closeout]))

// A skill that names a command the agent cannot run fails at the point of highest cost — mid-task,
// after the agent has already committed to the approach the skill prescribed.
function checkCommands(id, text, problems) {
  for (const [, name] of text.matchAll(/\bpnpm\s+([a-z][a-z0-9:._-]*)/g)) {
    if (PNPM_PASSTHROUGH.has(name)) continue
    if (!(name in scripts)) problems.push(`${id}: SKILL.md names \`pnpm ${name}\`, which is not a script in package.json`)
  }
}

// A report template is a fenced block of bare `Field:` lines. Three is the smallest count that
// reads as a contract rather than a stray colon in prose.
function hasReportTemplate(text) {
  for (const [, block] of text.matchAll(/```[a-z]*\n([\s\S]*?)```/g)) {
    const fields = block.split(/\r?\n/).filter((line) => /^[A-Za-z][^`]*:\s*$/.test(line))
    if (fields.length >= 3) return true
  }
  return false
}


// Closeout is the readiness contract one axis over: the manifest says what shape the skill owes the
// agent when it finishes, and the body has to actually carry that shape.
function checkCloseout(id, text, problems) {
  const closeout = closeoutById.get(id)
  if (!closeout) {
    problems.push(`${id}: no closeout declared in config/harness/manifest.json`)
    return
  }
  const body = sectionBody(text, CLOSE)
  if (body === null) {
    problems.push(`${id}: no \`## Close\` section — every skill must say how it ends and what it may not claim`)
    return
  }
  if (!body) problems.push(`${id}: \`## Close\` is empty — it must carry the stop rule for this skill`)
  const template = hasReportTemplate(text)
  if (closeout === 'report' && !template) {
    problems.push(`${id}: declares closeout \`report\` but carries no field template for the agent to fill`)
  }
  if (closeout === 'inline' && template) {
    problems.push(`${id}: declares closeout \`inline\` but carries a field template — it should be \`report\``)
  }
}

function sectionBody(text, heading) {
  const start = heading.exec(text)
  if (!start) return null
  const rest = text.slice(start.index + start[0].length)
  const next = /^##\s+/m.exec(rest)
  return (next ? rest.slice(0, next.index) : rest).trim()
}

function checkReadiness(id, text, problems) {
  const readiness = readinessById.get(id)
  if (!readiness) {
    problems.push(`${id}: no readiness declared in config/harness/manifest.json`)
    return
  }
  const declares = PRECONDITIONS.test(text)
  if (readiness === 'autonomous' && declares) {
    problems.push(`${id}: declares readiness \`autonomous\` but carries a Preconditions block — one of the two is wrong`)
  }
  if (readiness !== 'autonomous' && !declares) {
    problems.push(`${id}: declares readiness \`${readiness}\` but carries no \`## Preconditions\` block saying what to do when it is unmet`)
  }
  const lane = sectionBody(text, DEGRADED)
  if (readiness === 'gated' && !lane) {
    problems.push(
      `${id}: declares readiness \`gated\` but carries no \`## Degraded lane\` — a gated skill must say what it still does when its dependency is absent, not just stop`,
    )
  }
  if (readiness === 'autonomous' && lane) {
    problems.push(`${id}: declares readiness \`autonomous\` but carries a Degraded lane — it has no dependency to degrade from`)
  }
}

const problems = []
const ids = readdirSync(SKILLS).filter((name) => statSync(join(SKILLS, name)).isDirectory()).sort()

for (const id of ids) {
  const skillDir = join(SKILLS, id)
  const entry = join(skillDir, 'SKILL.md')
  if (!existsSync(entry)) {
    problems.push(`${id}: missing SKILL.md`)
    continue
  }
  const text = readFileSync(entry, 'utf8')
  for (const candidate of pathCandidates(text)) {
    if (!resolves(candidate, skillDir)) problems.push(`${id}: SKILL.md references a path that does not exist: ${candidate}`)
  }
  text.split(/\r?\n/).forEach((line, index) => {
    for (const [pattern, why] of FORBIDDEN) if (pattern.test(line)) problems.push(`${id}: SKILL.md:${index + 1} ${why}`)
    if (MIRROR_WRITE.test(line)) {
      problems.push(`${id}: SKILL.md:${index + 1} writes into the generated mirror — edit .claude/skills and run \`pnpm skills:sync\``)
    }
  })
  checkCommands(id, text, problems)
  checkReadiness(id, text, problems)
  checkCloseout(id, text, problems)
  checkDescriptor(id, skillDir, problems)
}

if (problems.length) {
  console.error('skill contract violations:')
  for (const problem of problems) console.error(`  - ${problem}`)
  process.exit(1)
}
const byReadiness = ids.reduce((counts, id) => {
  const readiness = readinessById.get(id)
  counts[readiness] = (counts[readiness] ?? 0) + 1
  return counts
}, {})
const summary = Object.entries(byReadiness).sort().map(([readiness, count]) => `${count} ${readiness}`).join(', ')
const reports = ids.filter((id) => closeoutById.get(id) === 'report').length
console.log(
  `skill contracts ok: ${ids.length} skills (${summary}; ${reports} report, ${ids.length - reports} inline) — ` +
    'paths resolve, commands exist, readiness/lanes and closeout match, every skill carries a Codex descriptor',
)
