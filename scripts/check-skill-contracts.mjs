// Contract ratchet for .claude/skills. check-skills-sync.mjs proves the mirror is byte-identical
// to the canonical copy; harness/check-manifest.mjs proves ids, inventory, and checksums line up.
// Neither one reads a skill body, so a skill can point every agent at a path that does not exist —
// which is how the session-memory skill shipped a write target that was both absent and gitignored,
// silently discarding the entry it was supposed to save. Run via `pnpm skills:contracts`.
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SKILLS = resolve(root, '.claude/skills')

// A skill writes paths relative to whichever tree it governs, so a candidate counts as dead only
// after failing every one of these plus the skill's own directory.
const SEARCH_ROOTS = ['', 'governance', 'apps/mobile']
// Generated or machine-local: absent in a clean checkout, so absence proves nothing.
const UNTRACKED = [/(^|\/)node_modules\//, /(^|\/)\.temp\//, /^\.codebase-memory\//]
// AGENTS.md Workspace Layout: `~/.codex/` is the CLI's own config home and the repo must never
// contain a matching path. `.gitignore` ignores it, so anything written there is lost.
const FORBIDDEN = [[/\.codex\//i, 'references a `.codex/` path — the repo must never contain one (AGENTS.md Workspace Layout)']]
// `.agents/` is generated by scripts/sync-skills.mjs; a skill must never send an agent to edit it.
const MIRROR_WRITE = /(^|\s)(cp|mv|rm|Write|Edit)\s[^\n]*\.agents\//
const DESCRIPTOR_KEYS = ['display_name', 'short_description', 'default_prompt']

function pathCandidates(text) {
  const found = new Set()
  for (const [, raw] of text.matchAll(/`([^`\n]+)`/g)) {
    const value = raw.trim()
    if (!value.includes('/')) continue
    if (/\s/.test(value)) continue
    if (/[<>*]/.test(value)) continue
    if (/^https?:/.test(value)) continue
    if (value.startsWith('@')) continue
    if (!/^[A-Za-z0-9._-]+(\/[A-Za-z0-9._-]+)+\/?$/.test(value)) continue
    if (value.split('/').includes('..')) continue
    // Two bare segments with no extension read as an upstream org/repo slug, not a repo path.
    if (!value.endsWith('/') && !/\.[A-Za-z0-9]+$/.test(value)) continue
    if (UNTRACKED.some((pattern) => pattern.test(value))) continue
    found.add(value)
  }
  return [...found]
}

function resolves(candidate, skillDir) {
  for (const base of SEARCH_ROOTS) if (existsSync(resolve(root, base, candidate))) return true
  return existsSync(resolve(skillDir, candidate))
}

function checkDescriptor(id, skillDir, problems) {
  const file = join(skillDir, 'agents', 'openai.yaml')
  if (!existsSync(file)) {
    problems.push(`${id}: missing agents/openai.yaml — Codex needs an interface descriptor for every skill`)
    return
  }
  const text = readFileSync(file, 'utf8')
  if (!/^interface:\s*$/m.test(text)) problems.push(`${id}: agents/openai.yaml has no top-level \`interface:\` block`)
  for (const key of DESCRIPTOR_KEYS) {
    const value = new RegExp(`^\\s+${key}:\\s*"?([^"\\n]*)"?\\s*$`, 'm').exec(text)?.[1]?.trim()
    if (!value) problems.push(`${id}: agents/openai.yaml is missing a non-empty ${key}`)
    else if (key === 'default_prompt' && !value.includes(`$${id}`)) {
      problems.push(`${id}: default_prompt must name the skill as $${id} so Codex can invoke it`)
    }
  }
}

if (!existsSync(SKILLS)) {
  console.error('canonical skills dir missing: .claude/skills')
  process.exit(1)
}

const problems = []
const ids = readdirSync(SKILLS).filter((name) => statSync(join(SKILLS, name)).isDirectory()).sort()

for (const id of ids) {
  const skillDir = join(SKILLS, id)
  const entry = join(skillDir, 'SKILL.md')
  if (!existsSync(entry)) {
    problems.push(`${id}: missing SKILL.md`)
    continue
  }
  const text = readFileSync(entry, 'utf8')
  for (const candidate of pathCandidates(text)) {
    if (!resolves(candidate, skillDir)) problems.push(`${id}: SKILL.md references a path that does not exist: ${candidate}`)
  }
  text.split(/\r?\n/).forEach((line, index) => {
    for (const [pattern, why] of FORBIDDEN) if (pattern.test(line)) problems.push(`${id}: SKILL.md:${index + 1} ${why}`)
    if (MIRROR_WRITE.test(line)) {
      problems.push(`${id}: SKILL.md:${index + 1} writes into the generated mirror — edit .claude/skills and run \`pnpm skills:sync\``)
    }
  })
  checkDescriptor(id, skillDir, problems)
}

if (problems.length) {
  console.error('skill contract violations:')
  for (const problem of problems) console.error(`  - ${problem}`)
  process.exit(1)
}
console.log(`skill contracts ok: ${ids.length} skills — paths resolve, no forbidden targets, every skill carries a Codex descriptor`)
