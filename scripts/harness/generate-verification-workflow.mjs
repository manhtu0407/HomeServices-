// Derives the verification release workflow from the strict one, so every deploy, attest, promote, and
// rollback step is the strict workflow's own text and the two cannot drift apart. The strict workflow is
// never edited by this script.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
export const STRICT_WORKFLOW = '.github/workflows/release-production.yml'
export const VERIFICATION_WORKFLOW = '.github/workflows/release-production-verification.yml'
export const CONFIRMATION_PHRASE = 'deploy-verification-release-to-production'

const UPLOAD = 'actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02 # v4'
const DOWNLOAD = 'actions/download-artifact@d3f86a106a0bac45b974a628896c90dbdf5c8093 # v4'
// GitHub expressions open with a dollar sign and a brace, which a template literal would interpolate.
const expression = (text) => text.replaceAll('@{{', '${{')

const PUSH_READINESS_ENV = String.raw`          EXPO_TOKEN: @{{ secrets.EXPO_TOKEN }}
          NESTSCOUT_ANDROID_FCM_V1_READY: @{{ vars.NESTSCOUT_ANDROID_FCM_V1_READY }}
          NESTSCOUT_IOS_APNS_READY: @{{ vars.NESTSCOUT_IOS_APNS_READY }}
          NESTSCOUT_PUSH_RECEIPT_RECONCILER_READY: @{{ vars.NESTSCOUT_PUSH_RECEIPT_RECONCILER_READY }}
`

const PUSH_READINESS_TESTS = String.raw`          test "$NESTSCOUT_ANDROID_FCM_V1_READY" = "true"
          test "$NESTSCOUT_IOS_APNS_READY" = "true"
          test "$NESTSCOUT_PUSH_RECEIPT_RECONCILER_READY" = "true"
`

const STRICT_TRANSACTION_STEPS = String.raw`      - name: Require executed transaction behavior before release mutation
        run: |
          node scripts/harness/transaction-critical-coverage.mjs --require-behavioral \
            --results artifacts/transactions/api-vitest.json \
            --results artifacts/transactions/mobile-jest.json
      - name: Preserve transaction runner evidence, including failures
        if: always()
        uses: ${UPLOAD}
        with:
          name: release-transaction-assertions-@{{ github.sha }}
          path: artifacts/transactions/*.json
          if-no-files-found: error
          retention-days: 90
`

const VERIFICATION_TRANSACTION_STEPS = String.raw`      - name: Require every bound transaction assertion to have executed and passed
        run: |
          node scripts/harness/transaction-critical-coverage.mjs --require-bound-assertions \
            --results artifacts/transactions/api-vitest.json \
            --results artifacts/transactions/mobile-jest.json
      - name: Record the acknowledged transaction gaps as a checksummed receipt
        run: |
          node scripts/harness/transaction-behavior-receipt.mjs \
            --results artifacts/transactions/api-vitest.json \
            --results artifacts/transactions/mobile-jest.json \
            --output artifacts/transactions-receipt/transaction-behavior-receipt.json
      - name: Preserve transaction runner evidence, including failures
        if: always()
        uses: ${UPLOAD}
        with:
          name: verification-transaction-assertions-@{{ github.sha }}-@{{ github.run_id }}
          path: artifacts/transactions/*.json
          if-no-files-found: error
          retention-days: 90
      - name: Preserve the transaction behavior receipt for the release job
        uses: ${UPLOAD}
        with:
          name: verification-transaction-behavior-@{{ github.run_id }}
          path: artifacts/transactions-receipt/transaction-behavior-receipt.json
          if-no-files-found: error
          retention-days: 90
`

const RECEIPT_DOWNLOAD_STEP = String.raw`      - name: Fetch the transaction behavior receipt written by this run's quality job
        uses: ${DOWNLOAD}
        with:
          name: verification-transaction-behavior-@{{ github.run_id }}
          path: artifacts/transactions-receipt
`

// The strict quality job fails fast while any catalog entry is not MAPPED. The verification lane releases while
// entries are PARTIAL and records each open gap in a checksummed receipt, so it must not carry that step.
const REQUIRE_MAPPED_STEP = String.raw`      # The behavioral gate below cannot pass while any transaction entry is unmapped, and that is
      # known from the manifest alone, so fail here instead of after the whole-workspace tests.
      - name: Require every transaction entry to be mapped before running tests
        run: node scripts/harness/transaction-critical-coverage.mjs --require-mapped
`

const STRICT_GATES = 'main-branch-merge,workspace-typecheck,workspace-tests,workspace-build,security,harness,edge-deno,database-reset,sql-verification,generated-types,expand-only,hosted-drift-baseline,production-ui-normality'

export function deriveVerificationWorkflow(strictText) {
  let text = strictText.replace(/\r\n/gu, '\n')

  text = replaceOnce(text, 'name: release-production\n', [
    '# Generated by scripts/harness/generate-verification-workflow.mjs from release-production.yml.',
    '# Edit the generator or the strict workflow, never this file.',
    'name: release-production-verification',
    '',
  ].join('\n'))
  text = replaceTopLevelBlock(text, 'on:\n', '\npermissions:\n', [
    'on:',
    '  workflow_dispatch:',
    '    inputs:',
    '      confirm:',
    `        description: Type ${CONFIRMATION_PHRASE} to release with acknowledged transaction gaps`,
    '        required: true',
    '        type: string',
    '',
  ].join('\n'))

  const reconcilerStart = text.indexOf('  stale-canary-reconciler:\n')
  const qualityStart = text.indexOf('  quality:\n')
  if (reconcilerStart < 0 || qualityStart <= reconcilerStart) throw new Error('strict workflow job layout changed: stale-canary-reconciler / quality')
  text = text.slice(0, reconcilerStart) + text.slice(qualityStart)

  const dispatchGuard = `    if: github.ref == 'refs/heads/main' && inputs.confirm == '${CONFIRMATION_PHRASE}'\n`
  const strictGuard = "    if: github.event_name != 'schedule' && github.ref == 'refs/heads/main'\n"
  text = replaceOnce(text, `    name: quality, security, integration, SQL, and immutable-source gates\n${strictGuard}`,
    `    name: quality, security, integration, SQL, and immutable-source gates\n${dispatchGuard}`)
  text = replaceOnce(text, `    needs: [quality, release-config-gate]\n${strictGuard}`, `    needs: [quality, release-config-gate]\n${dispatchGuard}`)
  text = replaceOnce(text, REQUIRE_MAPPED_STEP, '')

  text = replaceOnce(text, expression(STRICT_TRANSACTION_STEPS), expression(VERIFICATION_TRANSACTION_STEPS))
  text = replaceOnce(text, 'name: stage1-quality-${{ github.run_id }}', 'name: stage1-verification-quality-${{ github.run_id }}')

  text = replaceOnce(text, '      - name: Require complete encrypted Production release configuration\n',
    '      - name: Require the encrypted Production release configuration, recording push readiness as it is\n')
  text = replaceOnce(text, expression(PUSH_READINESS_ENV), '          EXPO_TOKEN: ${{ secrets.EXPO_TOKEN }}\n')
  text = replaceOnce(text, PUSH_READINESS_TESTS, '')

  text = replaceOnce(text,
    'node scripts/harness/release-bundle.mjs --environment production --output artifacts/release/release.json',
    'node scripts/harness/release-bundle.mjs --environment production --lane verification --output artifacts/release/release.json')

  const binaryStart = text.indexOf('      - name: Reuse or build exact iOS and Android store binaries for this merge\n')
  const attestStart = text.indexOf('      - name: Download and attest exact EAS binary artifacts\n')
  if (binaryStart < 0 || attestStart <= binaryStart) throw new Error('strict workflow step layout changed: EAS binary steps')
  text = text.slice(0, binaryStart) + reuseLatestStoreBinaries(text.slice(binaryStart, attestStart)) + text.slice(attestStart)

  text = replaceOnce(text, '      - name: Download and attest exact EAS binary artifacts\n',
    '      - name: Download and attest the latest existing EAS store binaries\n')
  text = replaceOnce(text, '--mode artifact-url --platform ios)', '--mode artifact-url --platform ios --relation latest_existing)')
  text = replaceOnce(text, '--mode artifact-url --platform android)', '--mode artifact-url --platform android --relation latest_existing)')
  text = replaceOnce(text,
    '            --android-artifact artifacts/mobile/nestscout.aab \\\n            --output artifacts/release/mobile-binary-attestation.json',
    '            --android-artifact artifacts/mobile/nestscout.aab \\\n            --relation latest_existing \\\n            --output artifacts/release/mobile-binary-attestation.json')

  text = replaceOnce(text, '      - name: Collect hosted production baseline\n', `${expression(RECEIPT_DOWNLOAD_STEP)}      - name: Collect hosted production baseline\n`)

  text = replaceOnce(text,
    `            --gates ${STRICT_GATES} \\\n            --output artifacts/release/promotion-packet.json`,
    `            --gates ${STRICT_GATES},transaction-bound-assertions \\\n` +
    '            --lane verification \\\n' +
    '            --transaction-behavior artifacts/transactions-receipt/transaction-behavior-receipt.json \\\n' +
    '            --output artifacts/release/promotion-packet.json')

  text = replaceOnce(text, 'name: stage1-production-release-${{ github.run_id }}', 'name: stage1-verification-release-${{ github.run_id }}')
  return text
}

// The strict step lists store builds of the release commit and builds what that commit lacks. The verification
// step keeps the same build-if-missing shell but lists the newest store builds of any commit, so an existing
// store binary is reused and only a platform that has none is built.
function reuseLatestStoreBinaries(step) {
  let next = replaceOnce(step, '      - name: Reuse or build exact iOS and Android store binaries for this merge\n',
    '      - name: Reuse the latest store binaries, building only a platform that has none\n')
  next = replaceOnce(next, ' --build-profile production --git-commit-hash "$GITHUB_SHA" \\\n', ' --build-profile production \\\n')
  next = replaceOnce(next, '--builds artifacts/mobile/eas-builds.json --mode missing)\n          if [ -n "$missing" ]; then',
    '--builds artifacts/mobile/eas-builds.json --mode missing \\\n            --relation latest_existing)\n          if [ -n "$missing" ]; then')
  return replaceOnce(next, '--builds artifacts/mobile/eas-builds.json --mode missing)"',
    '--builds artifacts/mobile/eas-builds.json --mode missing \\\n            --relation latest_existing)"')
}

// Replaces from a top-level key up to the next one, so an edit to the strict schedule or to the comments inside
// its trigger block does not break the derivation.
function replaceTopLevelBlock(text, startMarker, endMarker, replacement) {
  const start = text.indexOf(`\n${startMarker}`) + 1
  const end = text.indexOf(endMarker, start)
  if (start < 1 || end < 0 || text.indexOf(`\n${startMarker}`, start) >= 0) {
    throw new Error(`strict workflow no longer contains exactly one top-level block: ${startMarker.trim()}`)
  }
  return text.slice(0, start) + replacement + text.slice(end)
}

function replaceOnce(text, from, to) {
  const first = text.indexOf(from)
  if (first < 0 || text.indexOf(from, first + from.length) >= 0) {
    throw new Error(`strict workflow no longer contains exactly one of: ${from.split('\n')[0].trim()}`)
  }
  return text.slice(0, first) + to + text.slice(first + from.length)
}

export function readStrictWorkflow(root = ROOT) {
  return readFileSync(resolve(root, STRICT_WORKFLOW), 'utf8')
}

function main() {
  const generated = deriveVerificationWorkflow(readStrictWorkflow())
  const output = resolve(ROOT, VERIFICATION_WORKFLOW)
  if (process.argv.includes('--check')) {
    let current = ''
    try { current = readFileSync(output, 'utf8').replace(/\r\n/gu, '\n') } catch { /* missing counts as drift */ }
    if (current !== generated) {
      process.stderr.write(`${VERIFICATION_WORKFLOW} is out of date; run node scripts/harness/generate-verification-workflow.mjs\n`)
      process.exitCode = 1
    } else process.stdout.write(`${VERIFICATION_WORKFLOW} matches ${STRICT_WORKFLOW}\n`)
    return
  }
  writeFileSync(output, generated)
  process.stdout.write(`${VERIFICATION_WORKFLOW} written from ${STRICT_WORKFLOW}\n`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main() } catch (error) {
    process.stderr.write(`generate-verification-workflow failed: ${error.message}\n`)
    process.exitCode = 1
  }
}
