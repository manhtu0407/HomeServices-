import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const CONFIG_PATH = resolve(ROOT, 'config/harness/reliability.json')
const CAPABILITIES_PATH = resolve(ROOT, 'config/harness/capabilities.json')
const GENERATED_PATH = resolve(ROOT, 'supabase/functions/_shared/harness/reliability-registry.ts')
const normalizeSource = (value) => value.replace(/\r\n/gu, '\n')

export function checkReliabilityConfig(config, capabilities) {
  const problems = []
  const operationClasses = config.operation_classes ?? {}
  for (const [name, policy] of Object.entries(operationClasses)) {
    if (!Number.isInteger(policy.max_attempts) || policy.max_attempts < 1 || policy.max_attempts > 5) problems.push(`${name} max_attempts is invalid`)
    if (!Number.isInteger(policy.timeout_ms) || policy.timeout_ms < 100 || policy.timeout_ms > 120000) problems.push(`${name} timeout_ms is invalid`)
    if (name === 'money_impacting' && (!policy.idempotency || !policy.confirmation || policy.max_attempts !== 1)) problems.push('money_impacting must be idempotent, confirmed, and single-attempt')
    if (name === 'provider_call' && !policy.budget) problems.push('provider_call must reserve budget')
    if (policy.max_attempts > 1 && !policy.idempotency && !['pure_read', 'database_read', 'provider_call'].includes(name)) problems.push(`${name} retries require idempotency`)
  }
  for (const route of capabilities.entries ?? []) {
    const policy = operationClasses[route.operationClass]
    if (!policy) problems.push(`route ${route.kind} uses undeclared operation class ${route.operationClass}`)
    if (route.confirmationGate !== 'none' && !policy?.confirmation) problems.push(`route ${route.kind} requires confirmation but its operation policy does not`)
    if (route.operationClass === 'money_impacting' && route.confirmationGate === 'none') problems.push(`money route ${route.kind} has no confirmation gate`)
    if (route.sideEffectClass !== 'none' && route.sideEffectClass !== 'read-only' && route.operationClass !== 'provider_call' && policy?.max_attempts > 1 && !policy.idempotency) problems.push(`side-effect route ${route.kind} retries without idempotency`)
  }
  for (const [dependency, circuit] of Object.entries(config.dependencies ?? {})) {
    if (!Number.isInteger(circuit.threshold) || circuit.threshold < 1) problems.push(`${dependency} circuit threshold is invalid`)
    if (!Number.isInteger(circuit.window_ms) || circuit.window_ms < 1000) problems.push(`${dependency} circuit window is invalid`)
    if (!Number.isInteger(circuit.open_ms) || circuit.open_ms < 1000) problems.push(`${dependency} circuit open duration is invalid`)
    if (!Number.isInteger(circuit.half_open_probes) || circuit.half_open_probes < 1) problems.push(`${dependency} half-open probe count is invalid`)
  }
  if (!Number.isInteger(config.reservation_ttl_seconds) || config.reservation_ttl_seconds < 30) problems.push('reservation_ttl_seconds is invalid')
  return problems
}

export function renderReliabilityRegistry(config) {
  return `// Generated by scripts/harness/reliability-registry.mjs.\n` +
    `export const HARNESS_RELIABILITY_CONFIG = ${JSON.stringify(config, null, 2)} as const;\n` +
    `export type HarnessOperationClass = keyof typeof HARNESS_RELIABILITY_CONFIG.operation_classes;\n` +
    `export type HarnessDependency = keyof typeof HARNESS_RELIABILITY_CONFIG.dependencies;\n`
}

export function isReliabilityRegistryCurrent(actual, config) {
  return normalizeSource(actual) === renderReliabilityRegistry(config)
}

function main() {
  const config = JSON.parse(readFileSync(CONFIG_PATH, 'utf8'))
  const capabilities = JSON.parse(readFileSync(CAPABILITIES_PATH, 'utf8'))
  const problems = checkReliabilityConfig(config, capabilities)
  if (problems.length) {
    for (const problem of problems) console.error(`  - ${problem}`)
    process.exitCode = 1
    return
  }
  const expected = renderReliabilityRegistry(config)
  if (process.argv.includes('--write')) {
    writeFileSync(GENERATED_PATH, expected)
    console.log('wrote reliability registry')
    return
  }
  const actual = readFileSync(GENERATED_PATH, 'utf8')
  assert.ok(
    isReliabilityRegistryCurrent(actual, config),
    'reliability registry drift: run node scripts/harness/reliability-registry.mjs --write',
  )
  console.log(`reliability registry ok: ${Object.keys(config.operation_classes).length} operation classes, ${Object.keys(config.dependencies).length} dependencies`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
